export const validateFormField_1 = (fieldName, fieldValue, options = {}) => {
  if (options.required && (!fieldValue || String(fieldValue).trim() === '')) {
    return { isValid: false, error: fieldName + ' is required.' };
  }
  if (options.minLength && String(fieldValue).length < options.minLength) {
    return { isValid: false, error: fieldName + ' must be at least ' + options.minLength + ' characters.' };
  }
  if (options.pattern && !options.pattern.test(fieldValue)) {
    return { isValid: false, error: fieldName + ' format is invalid.' };
  }
  return { isValid: true, error: null };
};

